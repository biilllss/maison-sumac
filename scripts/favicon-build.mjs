/* ------------------------------------------------------------------ */
/*  Maison Sumac — favicon build script                                */
/*                                                                     */
/*  Single source of truth for every brand icon:                       */
/*    src/app/icon.svg        64px master (rounded cream tile)         */
/*    src/app/favicon.ico     16 / 32 / 48 (PNG-compressed ICO)        */
/*    src/app/icon.png        512 (rounded, Android / fallback)        */
/*    src/app/apple-icon.png  180 (full-bleed, iOS mask-safe)          */
/*    .qa/favicon-preview.png legibility check (dark + light strip)    */
/*                                                                     */
/*  Run:  node scripts/favicon-build.mjs                               */
/* ------------------------------------------------------------------ */

import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = process.cwd();
const APP = path.join(ROOT, "src", "app");
const QA = path.join(ROOT, ".qa");

/* Brand palette (mirrors globals.css tokens + BrandMark in icons.tsx) */
const CREAM = "#F6EFE3";
const OLIVE = "#3B4A32";
const TERRA = "#C4572F";

/* ------------------------------------------------------------------ */
/*  The mark — sumac berry sprig, faithful to the site's BrandMark:    */
/*  vertical olive stem sweeping into a right-hand hook, a large       */
/*  terracotta berry left of the stem, two smaller graded berries      */
/*  hanging on the right (solid / 0.85 / 0.65 — same trio as site).    */
/* ------------------------------------------------------------------ */
const MARK = `
    <path
      d="M30 51V27c0-8.5 5.5-12.5 12-10 1.8.6 2.6 2 2.4 3.8"
      fill="none" stroke="${OLIVE}" stroke-width="3.8" stroke-linecap="round"/>
    <circle cx="19.5" cy="35"   r="9.5" fill="${TERRA}"/>
    <circle cx="45.5" cy="24.5" r="6.5" fill="${TERRA}" opacity="0.85"/>
    <circle cx="47"   cy="36.5" r="7"   fill="${TERRA}" opacity="0.65"/>`;

/** Build one SVG source string.
 *  @param size   pixel size (written as width/height for crisp rasterizing)
 *  @param rx     corner radius of the cream tile (0 = full-bleed for iOS)
 *  @param scale  scale of the mark about the canvas center
 */
function buildSvg(size, rx, scale) {
  const wrap =
    scale === 1
      ? MARK
      : `<g transform="translate(32 32) scale(${scale}) translate(-32 -32)">${MARK}</g>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 64 64">
  <!-- Maison Sumac brand favicon — sumac sprig on cream (generated by scripts/favicon-build.mjs) -->
  <rect width="64" height="64" rx="${rx}" fill="${CREAM}"/>${wrap}
</svg>`;
}

/** PNG-compressed ICO container (valid for all modern browsers). */
function buildIco(pngs) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0); // reserved
  header.writeUInt16LE(1, 2); // type: icon
  header.writeUInt16LE(pngs.length, 4);

  const entries = [];
  const datas = [];
  let offset = 6 + 16 * pngs.length;
  for (const { size, buffer } of pngs) {
    const e = Buffer.alloc(16);
    e.writeUInt8(size >= 256 ? 0 : size, 0); // width  (0 = 256)
    e.writeUInt8(size >= 256 ? 0 : size, 1); // height
    e.writeUInt8(0, 2); // palette colors
    e.writeUInt8(0, 3); // reserved
    e.writeUInt16LE(1, 4); // color planes
    e.writeUInt16LE(32, 6); // bits per pixel
    e.writeUInt32LE(buffer.length, 8);
    e.writeUInt32LE(offset, 12);
    offset += buffer.length;
    entries.push(e);
    datas.push(buffer);
  }
  return Buffer.concat([header, ...entries, ...datas]);
}

async function renderPng(svg, size) {
  return sharp(Buffer.from(svg), { density: 72 * (size / 64) })
    .resize(size, size, { fit: "fill" })
    .png()
    .toBuffer();
}

async function main() {
  await Promise.all([mkdir(APP, { recursive: true }), mkdir(QA, { recursive: true })]);

  /* 1. Master SVG (what Next.js serves at /icon.svg) ------------------ */
  const master = buildSvg(64, 14, 1);
  await writeFile(path.join(APP, "icon.svg"), master + "\n", "utf8");

  /* 2. favicon.ico — 16 / 32 / 48 ------------------------------------ */
  const icoSizes = [16, 32, 48];
  const icoPngs = [];
  for (const s of icoSizes) {
    icoPngs.push({ size: s, buffer: await renderPng(buildSvg(s, 14, 1), s) });
  }
  await writeFile(path.join(APP, "favicon.ico"), buildIco(icoPngs));

  /* 3. Android / general fallback 512 -------------------------------- */
  await writeFile(
    path.join(APP, "icon.png"),
    await renderPng(buildSvg(512, 112, 1), 512)
  );

  /* 4. Apple touch icon — full-bleed, mark enlarged (iOS crops edges) */
  await writeFile(
    path.join(APP, "apple-icon.png"),
    await renderPng(buildSvg(180, 0, 1.16), 180)
  );

  /* 5. QA preview — each ICO size upscaled nearest x8:
        top row on olive (dark tab bar), bottom row on cream (light tab) */
  const cell = 128;
  const ups = [];
  for (const s of icoSizes) {
    const src = icoPngs.find((p) => p.size === s).buffer;
    ups.push(await sharp(src).resize(cell, cell, { kernel: "nearest" }).png().toBuffer());
  }
  await sharp({
    create: {
      width: cell * 3 + 32,
      height: cell * 2 + 24,
      channels: 4,
      background: OLIVE,
    },
  })
    .composite([
      ...ups.map((input, i) => ({ input, left: 8 + i * (cell + 8), top: 8 })),
      ...ups.map((input, i) => ({ input, left: 8 + i * (cell + 8), top: cell + 16 })),
    ])
    .png()
    .toFile(path.join(QA, "favicon-preview.png"));

  console.log(
    "favicon assets written: icon.svg, favicon.ico (16/32/48), icon.png 512, apple-icon.png 180, .qa/favicon-preview.png"
  );
}

await main();
